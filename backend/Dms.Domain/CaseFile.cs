namespace Dms.Domain;

/// <summary>
/// **المعاملة** — خيطُ مراسلاتٍ يجمع كتباً واردة وصادرة في قضيةٍ واحدة (ADR-045).
/// </summary>
/// <remarks>
/// <para>
/// 🔴 **لماذا حاوٍ صريح لا روابط ثنائية؟** لأن المطلوب «افتح أيّ كتابٍ تَرَ البقيّة»، وخمسةُ
/// كتبٍ تحتاج **عشرة** روابط ثنائية ليتحقّق ذلك (وعشرةٌ تحتاج ٤٥) — فلا يفعلها أحد. والبديل
/// العمليّ سلسلةٌ يربط فيها كلٌّ سابقَه، **ففتحُ الأول لا يُظهر الأخير** وهو عين المطلوب.
/// الحاوي يجعلها **خمسَ انتماءات** ويُظهر الكلَّ للكلّ بالبناء.
/// </para>
/// <para>
/// ⚠️ **والاسم `CaseFile` لا `Subject`**: <c>IncomingBook.Subject</c> و<c>OutgoingBook.Subject</c>
/// موجودان أصلاً ويُعرضان بعنوان **«الموضوع»** في كل شاشة وتقرير — فتسميةُ هذا «الموضوع»
/// كانت تُنتج بطاقةً فيها الكلمة بمعنيين. والعربية **«المعاملة»** (قرار المالك).
/// </para>
/// <para>
/// ⚠️ **بلا حالةٍ وبلا رقمٍ تسلسليّ في v1** (قرار مؤجَّل): الحالة تُكرّر حالات الكتب وتنحرف
/// عنها، والرقمُ يُشبه أرقام الكتب فيُخلط بها. **العنوان هويّتها.**
/// </para>
/// </remarks>
public class CaseFile
{
    public int CaseFileId { get; set; }

    /// <summary>الشركة المالكة (عزل صفّي — لكل شركة معاملاتها).</summary>
    public int CompanyId { get; set; }

    /// <summary>عنوانٌ يكتبه المُنشئ.</summary>
    /// <remarks>
    /// 🔐 **مُهيّأٌ بعنوان أوّل كتاب لكنه يُعرض للمُنشئ ويُعدَّل قبل الحفظ** (قرار المالك):
    /// الاشتقاقُ الصامت كان **يُسرّب موضوع كتابٍ محجوب** — فمن يرى الكتاب الثاني لاحقاً يقرأ
    /// موضوع الأول في العنوان، وقاعدةُ «المحجوب بالعدد فقط» تُخترق من الباب الأمامي.
    /// وبعرضه على المُنشئ (وهو يرى الكتابين أصلاً) **يقع قرار الإفصاح على إنسان**.
    /// </remarks>
    public string Title { get; set; } = string.Empty;

    public string? Notes { get; set; }

    public int CreatedByUserId { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime? UpdatedAt { get; set; }

    /// <summary>تزامنٌ متفائل — **لأجل الدمج تحديداً**.</summary>
    /// <remarks>
    /// 🔴 دمجان متزامنان (أ←ب) و(ب←أ) بلا حارسٍ يحذفان الاثنتين أو يُديران الكتب بينهما.
    /// والدمج يقع داخل معاملةٍ بقفلٍ مرتّب، وهذا حزامٌ ثانٍ فوقه.
    /// </remarks>
    public byte[]? RowVersion { get; set; }

    public bool IsDeleted { get; set; }
    public int? DeletedByUserId { get; set; }
    public DateTime? DeletedAt { get; set; }
}
