namespace Dms.Domain;

/// <summary>
/// أنواع المستندات الافتراضية التي تُبذر لكل شركة جديدة.
/// </summary>
/// <remarks>
/// ⚠️ **سبب وجود هذا الملف:** الحقل ونقاط الـAPI والفلترة كانت مبنية منذ البداية، لكن القائمة
/// تبدأ **فارغة** ولا شاشة تملؤها — فبقيت القائمة المنسدلة فارغة أبداً، و**صفر** كتاب من 43
/// يحمل نوعاً. ميزة كاملة معطّلة لأن لا أحد يستطيع إدخال أول قيمة فيها.
///
/// هذه القائمة **نقطة انطلاق لا قيد**: المالك يعدّلها ويحذف منها ويضيف إليها من
/// الإعدادات ← أنواع المستندات. اختيرت من الشائع في مراسلات شركات المقاولات.
/// </remarks>
public static class DefaultDocumentTypes
{
    public static readonly string[] Names =
    [
        "كتاب رسمي",
        "فاتورة",
        "عقد",
        "مخطّط",
        "طلب عرض سعر",
        "تقرير",
        "شكوى",
        "أخرى",
    ];

    /// <summary>يُنشئ كيانات الأنواع الافتراضية لشركة بعينها (بلا حفظ — المُستدعي يحفظ).</summary>
    public static IEnumerable<DocumentType> For(int companyId) =>
        Names.Select(n => new DocumentType { CompanyId = companyId, Name = n });
}
